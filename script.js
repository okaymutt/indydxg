/* ANDROID LOCK-SCREEN MEDIA CONTROLS */

function updateMediaSession(track, release) {
  if (!("mediaSession" in navigator)) return;

  if ("MediaMetadata" in window) {
    const artwork = release.cover
      ? [{
          src: new URL(release.cover, document.baseURI).href,
          type: "image/png"
        }]
      : [];

    navigator.mediaSession.metadata = new MediaMetadata({
      title: track.title,
      artist: "indydxg",
      album: release.title,
      artwork: artwork
    });
  }

  navigator.mediaSession.playbackState = "playing";
}

function playTrackAt(index) {
  if (!currentRelease) return;

  if (index < 0 || index >= currentRelease.tracks.length) return;

  const releaseIndex = releases.indexOf(currentRelease);
  const releaseElements = releaseList.querySelectorAll(".release");
  const releaseElement = releaseElements[releaseIndex];

  const buttons = releaseElement?.querySelectorAll(".track-button");
  const button = buttons?.[index];

  if (button) {
    playTrack(currentRelease.tracks[index], currentRelease, button);
  }
}

function setMediaAction(action, callback) {
  if (!("mediaSession" in navigator)) return;

  try {
    navigator.mediaSession.setActionHandler(action, callback);
  } catch (error) {
    // Ignore playback actions unsupported by this browser.
  }
}

setMediaAction("play", () => {
  audio.play().catch(() => {});
});

setMediaAction("pause", () => {
  audio.pause();
});

setMediaAction("previoustrack", () => {
  if (!currentRelease || currentTrackIndex < 0) return;

  // Restart the current song if it has played for more than 3 seconds.
  if (audio.currentTime > 3) {
    audio.currentTime = 0;
    return;
  }

  // Otherwise, go to the previous song in this album.
  if (currentTrackIndex > 0) {
    playTrackAt(currentTrackIndex - 1);
  } else {
    audio.currentTime = 0;
  }
});

setMediaAction("nexttrack", () => {
  if (!currentRelease || currentTrackIndex < 0) return;

  const nextIndex = currentTrackIndex + 1;

  if (nextIndex < currentRelease.tracks.length) {
    playTrackAt(nextIndex);
  }
});


function timeLabel(seconds) {
  if (!Number.isFinite(seconds) || seconds < 0) return "00:00";
  const m = Math.floor(seconds / 60);
  const s = Math.floor(seconds % 60);
  return `${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}`;
}

function playTrack(track, release, button) {
  if (!track.src || track.src.includes("track-one.mp3") || track.src.includes("track-two.mp3")) {
    playerState.textContent = "ADD YOUR AUDIO FILE";
    nowTitle.textContent = track.title;
    nowRelease.textContent = release.title;
    nowDetail.textContent = `Put the audio file in music/ and update its src in script.js.`;
    return;
  }
  
  currentRelease = release;
  currentTrackIndex = release.tracks.indexOf(track);
  
  if (activeButton) activeButton.removeAttribute("aria-current");
  activeButton = button;
  if (activeButton) activeButton.setAttribute("aria-current", "true");
  audio.src = track.src;
  if (release.cover) {
  visualizerCover.src = release.cover;
  visualizerCover.hidden = false;
  visualizerGif.hidden = true;
} else {
  visualizerCover.hidden = true;
  visualizerGif.hidden = false;
}
  audio.load();
  nowTitle.textContent = track.title;
  nowRelease.textContent = release.title;
  nowDetail.textContent = `${release.year} / ${track.format || "AUDIO"}`;
  formatLabel.textContent = track.format || "AUDIO";
  updateMediaSession(track, release);
  playButton.disabled = false;
  seek.disabled = false;
  playerState.textContent = "LOADING TRACK";
  audio.play().then(() => {
    playButton.textContent = "Ⅱ";
    playerState.textContent = "NOW PLAYING";
  }).catch(() => {
    playerState.textContent = "PRESS PLAY TO START";
    playButton.textContent = "▶";
  });
}

function renderReleases() {
  releaseList.innerHTML = "";
  let releaseNumber = 0;
  releases.forEach((release) => {
    releaseNumber += 1;
    const article = document.createElement("article");
    article.className = "release";
    const cover = release.cover ? document.createElement("img") : document.createElement("div");
    cover.className = "release-cover" + (release.cover ? "" : " cover-placeholder");
    if (release.cover) {
      cover.src = release.cover;
      cover.alt = `${release.title} cover artwork`;
    } else {
      cover.setAttribute("aria-hidden", "true");
      cover.textContent = "ID//";
    }

    const body = document.createElement("div");
    const type = document.createElement("div");
    type.className = "release-type";
    type.textContent = `${release.type} / ${release.year}`;
    const title = document.createElement("h3");
    title.textContent = release.title;
    const description = document.createElement("p");
    description.textContent = `${release.tracks.length} TRACK${release.tracks.length === 1 ? "" : "S"}`;
    const trackList = document.createElement("div");
    trackList.className = "track-list";

    release.tracks.forEach((track, index) => {
      const button = document.createElement("button");
      button.className = "track-button";
      button.type = "button";
      button.textContent = `${String(index + 1).padStart(2, "0")}  ${track.title}  ▶`;
      button.addEventListener("click", () => playTrack(track, release, button));
      trackList.appendChild(button);
    });

    body.append(type, title, description, trackList);
    const side = document.createElement("div");
    side.className = "release-side";
    side.textContent = `NO. ${String(releaseNumber).padStart(2, "0")}`;
    article.append(cover, body, side);
    releaseList.appendChild(article);
  });
  document.getElementById("release-count").textContent = `01—${String(releaseNumber).padStart(2, "0")}`;
}

playButton.addEventListener("click", () => {
  if (!audio.src) return;
  if (audio.paused) {
    audio.play().then(() => {
      playButton.textContent = "Ⅱ";
      playerState.textContent = "NOW PLAYING";
    }).catch(() => { playerState.textContent = "UNABLE TO PLAY"; });
  } else {
    audio.pause();
    playButton.textContent = "▶";
    playerState.textContent = "PAUSED";
  }
});


audio.addEventListener("play", () => {
  if ("mediaSession" in navigator) {
    navigator.mediaSession.playbackState = "playing";
  }

  playButton.textContent = "Ⅱ";
});

audio.addEventListener("pause", () => {
  if ("mediaSession" in navigator) {
    navigator.mediaSession.playbackState = "paused";
  }

  playButton.textContent = "▶";
});


audio.addEventListener("loadedmetadata", () => {
  durationEl.textContent = timeLabel(audio.duration);
  playerState.textContent = "READY";
});
audio.addEventListener("timeupdate", () => {
  currentTimeEl.textContent = timeLabel(audio.currentTime);
  if (Number.isFinite(audio.duration) && audio.duration > 0) {
    seek.value = String(Math.round((audio.currentTime / audio.duration) * 1000));
  }
});

audio.addEventListener("error", () => {
  playerState.textContent = "AUDIO FILE NOT FOUND";
  nowDetail.textContent = "Check the file name and path in script.js.";
});
seek.addEventListener("input", () => {
  if (Number.isFinite(audio.duration) && audio.duration > 0) {
    audio.currentTime = (Number(seek.value) / 1000) * audio.duration;
  }
});
volume.value = "1";
audio.volume = 1;

volume.addEventListener("input", () => {
  audio.volume = Number(volume.value);
});
document.getElementById("year").textContent = new Date().getFullYear();
renderReleases();


/* AUTOMATIC NEXT TRACK — INCLUDING BACKGROUND PLAYBACK */

audio.addEventListener("ended", () => {
  seek.value = "0";
  currentTimeEl.textContent = "00:00";

  if (!currentRelease || currentTrackIndex < 0) {
    playButton.textContent = "▶";
    playerState.textContent = "TRACK ENDED";
    return;
  }

  const nextIndex = currentTrackIndex + 1;

  // Play the next track in the current album.
  if (nextIndex < currentRelease.tracks.length) {
    playTrackAt(nextIndex);
    return;
  }

  // The album has finished.
  playButton.textContent = "▶";
  playerState.textContent = "ALBUM COMPLETE";
  currentTrackIndex = -1;

  if ("mediaSession" in navigator) {
    navigator.mediaSession.playbackState = "paused";
  }
});

